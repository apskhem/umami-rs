/// Upstream's `DEFAULT_PAGE_SIZE`.
pub const DEFAULT_PAGE_SIZE: i64 = 20;

/// Prisma's `@default(now())` and `@updatedAt`: generated by the client, at
/// millisecond precision.
pub fn now() -> DateTime<Utc> {
  Utc::now().trunc_subsecs(3)
}

/// Upstream's `QueryFilters`, as far as list queries use them.
#[derive(Debug, Clone, Default)]
pub struct Filters {
  pub page: Option<i64>,
  pub page_size: Option<i64>,
  pub order_by: Option<String>,
  pub sort_descending: Option<bool>,
  pub search: Option<String>,
}

impl Filters {
  /// Upstream's `sanitizeSortFilters`: keeps `orderBy` only if it names an
  /// allowed field, otherwise falls back to the defaults (or drops sorting).
  pub fn sanitize(
    mut self,
    allowed: &[&str],
    default_order_by: Option<&str>,
    default_descending: Option<bool>,
  ) -> Self {
    let is_allowed = self.order_by.as_deref().is_some_and(|field| allowed.contains(&field));

    if !is_allowed {
      self.order_by = default_order_by.map(str::to_owned);
      self.sort_descending = default_descending;
    }

    self
  }

  fn size(&self) -> i64 {
    self.page_size.unwrap_or(DEFAULT_PAGE_SIZE)
  }

  fn page_number(&self) -> i64 {
    self.page.unwrap_or(1)
  }

  /// An `ilike` pattern matching the search text anywhere, literally.
  /// (Upstream's Prisma `contains` leaves `%` and `_` as wildcards.)
  fn search_pattern(&self) -> Option<String> {
    self.search.as_deref().filter(|s| !s.is_empty()).map(|s| {
      let escaped = s.replace('\\', "\\\\").replace('%', "\\%").replace('_', "\\_");
      format!("%{escaped}%")
    })
  }

  /// `order by` for the requested field, or `default` (a trusted SQL fragment),
  /// then `key` (the primary key) to break ties, so pages never overlap.
  /// Callers sanitize `orderBy` first, so only known fields reach `column`.
  fn push_order(
    &self,
    builder: &mut QueryBuilder<Postgres>,
    column: fn(&str) -> Option<&'static str>,
    default: &str,
    key: &str,
  ) {
    let requested = self.order_by.as_deref().and_then(column).map(|column| {
      let direction = if self.sort_descending == Some(true) {
        "desc"
      } else {
        "asc"
      };
      format!("{column} {direction}")
    });

    let order = requested.as_deref().unwrap_or(default);
    builder.push(format!(" order by {order}, {key}"));
  }

  /// `limit`/`offset` for the requested page (`take`/`skip` in Prisma).
  fn push_limit(&self, builder: &mut QueryBuilder<Postgres>) {
    let size = self.size();
    let offset = size.saturating_mul(self.page_number() - 1);

    builder
      .push(" limit ")
      .push_bind(size)
      .push(" offset ")
      .push_bind(offset);
  }

  /// Upstream's `pagedQuery` result: `{ data, count, page, pageSize, orderBy, search }`.
  pub fn page(&self, data: Vec<Value>, count: i64) -> Value {
    let mut page = json!({
        "data": data,
        "count": count,
        "page": self.page_number(),
        "pageSize": self.size(),
    });

    if let Some(order_by) = &self.order_by {
      page["orderBy"] = json!(order_by);
    }
    if let Some(search) = &self.search {
      page["search"] = json!(search);
    }

    page
  }
}

/// A model as JSON, its fields in declaration (schema) order.
fn model_json(model: &impl serde::Serialize) -> Map<String, Value> {
  into_map(serde_json::to_value(model).expect("models serialize to JSON"))
}

/// Model fields as API names to columns, for `orderBy`.
fn sort_column(field: &str) -> Option<&'static str> {
  Some(match field {
    "name" => "name",
    "domain" => "domain",
    "description" => "description",
    "type" => "type",
    "slug" => "slug",
    "url" => "url",
    "username" => "username",
    "role" => "role",
    "createdAt" => "created_at",
    _ => return None,
  })
}

/// The fields of a JSON object literal (models are built with `json!` in schema
/// field order).
fn into_map(value: Value) -> Map<String, Value> {
  match value {
    Value::Object(map) => map,
    _ => unreachable!("built from an object literal"),
  }
}

/// Deletes the rows of `table` whose `column` is one of `ids`.
async fn delete_where(tx: &mut PgConnection, table: &str, column: &str, ids: &[Uuid]) -> sqlx::Result<()> {
  sqlx::query(sqlx::AssertSqlSafe(format!(
    r#"delete from "{table}" where {column} = any($1)"#
  )))
  .bind(ids)
  .execute(&mut *tx)
  .await?;

  Ok(())
}

#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn sanitizes_sorting_like_upstream() {
    let requested = |order_by: &str| {
      Filters {
        order_by: Some(order_by.to_owned()),
        sort_descending: Some(true),
        ..Filters::default()
      }
    };

    let kept = requested("name").sanitize(&["name"], Some("createdAt"), Some(false));
    assert_eq!(kept.order_by.as_deref(), Some("name"));
    assert_eq!(kept.sort_descending, Some(true));

    let fallback = requested("password").sanitize(&["name"], Some("createdAt"), Some(false));
    assert_eq!(fallback.order_by.as_deref(), Some("createdAt"));
    assert_eq!(fallback.sort_descending, Some(false));

    let dropped = requested("password").sanitize(&["name"], None, None);
    assert_eq!(dropped.order_by, None);
    assert_eq!(dropped.sort_descending, None);
  }

  #[test]
  fn pages_like_upstream() {
    let filters = Filters {
      page: Some(2),
      search: Some(String::new()),
      ..Filters::default()
    };

    assert_eq!(
      filters.page(vec![], 0),
      json!({ "data": [], "count": 0, "page": 2, "pageSize": 20, "search": "" })
    );
    assert_eq!(filters.search_pattern(), None);
  }

  #[test]
  fn searches_literally() {
    let search = |text: &str| {
      Filters {
        search: Some(text.to_owned()),
        ..Filters::default()
      }
      .search_pattern()
    };

    assert_eq!(search("a_b%c\\d").as_deref(), Some("%a\\_b\\%c\\\\d%"));
  }
}
