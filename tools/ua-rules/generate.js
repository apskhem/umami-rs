// Generates `umami-server/src/collect/ua/rules.rs` from the user-agent libraries
// upstream Umami uses, so the Rust port classifies browsers, operating systems,
// devices and bots exactly as they do.
//
//   npm ci --ignore-scripts && npm run generate
//
// Device types come from ua-parser-js 1.x (MIT). Upstream uses 2.x, which is
// AGPL-licensed and therefore not ported; `npm run fixtures` measures how often
// the two disagree.

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { translate } = require('./translate');

const ROOT = path.resolve(__dirname, '../..');
const OUT_DIR = path.join(ROOT, 'umami-server/src/collect/ua');

// Runs a CommonJS file in a sandbox after exposing its private variables on the global object.
function loadPrivate(file, exposures) {
  let source = fs.readFileSync(file, 'utf8');

  for (const [declaration, name] of exposures) {
    if (!source.includes(declaration)) {
      throw new Error(`\`${declaration}\` not found in ${file}`);
    }
    source = source.replace(declaration, `${declaration.replace(/=\s*[[{]$/, '')}= globalThis.${name} = ${declaration.slice(-1)}`);
  }

  const sandbox = { exports: {}, module: { exports: {} }, process };
  vm.runInNewContext(source, sandbox);

  return sandbox;
}

function packageFile(name, file) {
  return path.join(path.dirname(require.resolve(`${name}/package.json`)), file);
}

function version(name) {
  return require(`${name}/package.json`).version;
}

function rustString(value) {
  let hashes = '';
  while (value.includes(`"${hashes}`)) hashes += '#';
  return `r${hashes}"${value}"${hashes}`;
}

function pattern(regex) {
  const { pattern, fancy } = translate(regex);
  return `Pattern { source: ${rustString(pattern)}, fancy: ${fancy} }`;
}

// detect-browser: ordered (name, regex) rules for browsers and operating systems.
const detectBrowser = loadPrivate(packageFile('detect-browser', 'index.js'), [
  ['var userAgentRules = [', 'userAgentRules'],
  ['var operatingSystemRules = [', 'operatingSystemRules'],
]);

// isbot: the pattern is the alternation of these entries, matched case-insensitively.
const isbotList = require('isbot').list;

// ua-parser-js 1.x: device rules are pairs of (regexes, properties).
const uaParser = loadPrivate(packageFile('ua-parser-js-v1', 'src/ua-parser.js'), [
  ['var regexes = {', 'regexes'],
]);

function deviceKind(props) {
  const index = props.findIndex(prop => (typeof prop === 'string' ? prop : prop[0]) === 'type');

  if (index === -1) {
    return 'DeviceKind::Unknown';
  }

  const prop = props[index];
  const group = index + 1;

  if (typeof prop === 'string') {
    return `DeviceKind::Group(${group})`;
  }

  if (prop.length === 2 && typeof prop[1] === 'string') {
    return `DeviceKind::Const(${rustString(prop[1])})`;
  }

  if (prop.length === 3 && typeof prop[1] === 'function' && prop[1].name === 'strMapper') {
    const map = prop[2];
    const entries = Object.keys(map)
      .filter(key => key !== '*')
      .map(key => {
        const needles = [].concat(map[key]).map(rustString).join(', ');
        const result = key === '?' ? 'None' : `Some(${rustString(key)})`;
        return `(${result}, &[${needles}])`;
      });
    const fallback = '*' in map ? `Some(${rustString(map['*'])})` : 'None';

    return `DeviceKind::Map { group: ${group}, entries: &[${entries.join(', ')}], fallback: ${fallback} }`;
  }

  throw new Error(`unsupported device type property: ${prop}`);
}

const deviceRules = [];
const { device } = uaParser.regexes;

for (let i = 0; i < device.length; i += 2) {
  const patterns = device[i].map(pattern).join(',\n            ');
  deviceRules.push(
    `    DeviceRule {\n        patterns: &[\n            ${patterns},\n        ],\n        kind: ${deviceKind(device[i + 1])},\n    },`,
  );
}

const namedRules = rules =>
  rules.map(([name, regex]) => `    (${rustString(name)}, ${pattern(regex)}),`).join('\n');

const output = `// @generated by tools/ua-rules/generate.js. Do not edit.
//
// Ported from (see NOTICE.md):
// - detect-browser ${version('detect-browser')}
// - isbot ${version('isbot')}
// - ua-parser-js ${version('ua-parser-js-v1')}

use super::{DeviceKind, DeviceRule, Pattern};

/// detect-browser \`userAgentRules\`, in order.
pub(super) static BROWSER_RULES: &[(&str, Pattern)] = &[
${namedRules(detectBrowser.userAgentRules)}
];

/// detect-browser \`operatingSystemRules\`, in order.
pub(super) static OS_RULES: &[(&str, Pattern)] = &[
${namedRules(detectBrowser.operatingSystemRules)}
];

/// isbot pattern entries (each matched case-insensitively).
pub(super) static BOT_PATTERNS: &[Pattern] = &[
${isbotList.map(entry => `    ${pattern(new RegExp(entry, 'i'))},`).join('\n')}
];

/// ua-parser-js device rules, in order.
pub(super) static DEVICE_RULES: &[DeviceRule] = &[
${deviceRules.join('\n')}
];
`;

const license = (name, file) => fs.readFileSync(packageFile(name, file), 'utf8').trim();

const notice = `# Third-party notices

\`rules.rs\` is generated from the following packages by \`tools/ua-rules\`.

## detect-browser ${version('detect-browser')}

${license('detect-browser', 'LICENSE')}

## ua-parser-js ${version('ua-parser-js-v1')}

${license('ua-parser-js-v1', 'license.md')}

## isbot ${version('isbot')}

${license('isbot', 'LICENSE')}
`;

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(path.join(OUT_DIR, 'rules.rs'), output);
fs.writeFileSync(path.join(OUT_DIR, 'NOTICE.md'), notice);

console.log(
  `browser=${detectBrowser.userAgentRules.length} os=${detectBrowser.operatingSystemRules.length} ` +
    `bot=${isbotList.length} device=${deviceRules.length}`,
);
